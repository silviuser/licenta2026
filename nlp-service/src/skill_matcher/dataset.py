"""Training-dataset domain types and JSONL I/O for Module 3 / Step 3.

This module defines the **on-disk** representation of the supervised
training corpus consumed by Step 5 (Colab fine-tuning) of the
``skill_matcher`` pipeline:

* :class:`TrainingPair` — one ``(text_span, esco_uri)`` **positive**
  pair, generated by re-using a Module 2 ``SkillMatch`` whose
  confidence is at or above the build script's ``--min-confidence``
  threshold.
* :class:`HardNegative` — one ``(text_span, wrong_esco_uri)`` pair
  produced by the hard-negative miner. Carries the strategy that
  selected the distractor and a foreign key back to its paired
  positive so ablation studies (e.g. "what if we drop the FP-catalogue
  strategy?") can filter the corpus surgically.
* :class:`TrainingDataset` — the JSONL file wrapper: list of pairs
  plus build provenance (timestamp, CLI config, split name, counts).

The module has **no ML dependencies** — pydantic + stdlib only. Step
4 introduces torch / sentence-transformers; Step 3 just emits text.

The disk format is JSON-lines (one pair per line) so the dataset
streams cleanly in the Step 5 Colab notebook (``datasets.load_dataset
("json", data_files=...)``). Pair ordering inside a JSONL file is
**deterministic** by ``(cv_id, span_start, span_end, pair_type,
esco_uri)`` so re-builds with the same seed and inputs produce
byte-identical files — the thesis-defence reproducibility answer
hinges on this.
"""

from __future__ import annotations

import hashlib
import json
from datetime import datetime
from pathlib import Path
from typing import Annotated, Any, Literal

import structlog
from pydantic import BaseModel, Field, TypeAdapter, ValidationError, field_validator

from skill_matcher.models import Language

logger = structlog.get_logger(__name__)


# ---------------------------------------------------------------------------
# Type aliases
# ---------------------------------------------------------------------------

NegativeStrategy = Literal[
    "same_category_esco",
    "module2_fp_catalogue",
    "random_in_corpus",
]
"""How the hard-negative miner selected the distractor URI for a positive.

* ``"same_category_esco"`` — sibling URI under the same L2 ancestor of the
  positive in the ESCO hierarchy. Highest-signal: teaches the encoder
  fine-grained distinctions inside a category (e.g. Python vs Ruby under
  *computer programming*).
* ``"module2_fp_catalogue"`` — wrong URI drawn from the Module 2 FP
  families documented in the patch-round validation report and encoded
  in ``data/training/known_false_positives.yaml``. Teaches the encoder
  to overcome polysemy that the lexical baseline gets wrong.
* ``"random_in_corpus"`` — uniform random URI from the full ESCO + CUST
  universe. Used as a fallback when strategies 1 and 2 cannot produce
  enough candidates for a given positive. Easiest negative for the
  model — useful for cold-start but its share is monitored.
"""

Section = Literal[
    "skills", "experience", "education", "profile", "languages", "other"
]
"""CV section labels echoed from Module 2's
:data:`skill_extractor.models.SectionLabel`. Duplicated here so consumers
do not need a runtime dependency on Module 2's symbol layout."""


