# Pair models
# ---------------------------------------------------------------------------


class _PairBase(BaseModel):
    """Fields shared between :class:`TrainingPair` and :class:`HardNegative`.

    Splitting these out lets the JSONL loader pydantic-validate every
    row through the discriminated union ``TrainingPair | HardNegative``
    without re-stating field definitions.

    All confidences live in ``[0.0, 1.0]`` to mirror Module 2's
    ``SkillMatch.confidence`` and Module 3's
    ``MatchCandidate.confidence`` conventions.
    """

    pair_id: str = Field(
        min_length=1,
        description=(
            "Stable deterministic identifier for this pair — SHA-1 of "
            "``f'{cv_id}|{span_start}|{span_end}|{esco_uri}|{pair_type}'`` "
            "truncated to 16 hex chars. Lets :class:`HardNegative` "
            "foreign-key back to its paired positive."
        ),
    )
    cv_id: str = Field(
        min_length=1,
        description=(
            "Stable identifier for the source CV — e.g. ``\"train_cv042\"``. "
            "Always starts with ``\"train_\"`` for training pairs to keep "
            "any future contamination check by-prefix obvious."
        ),
    )
    text_span: str = Field(
        min_length=1,
        description=(
            "The literal CV text the encoder will see as the anchor of "
            "this pair. For Module-2-derived positives this is the "
            "surface form Module 2 matched (``SkillMatch.matched_text``)."
        ),
    )
    span_start: int = Field(
        ge=0,
        description="Character offset (inclusive) into the source CV text.",
    )
    span_end: int = Field(
        gt=0,
        description="Character offset (exclusive) into the source CV text.",
    )
    context_before: str = Field(
        default="",
        description=(
            "Up to ~50 chars of CV text immediately preceding "
            ":attr:`text_span`, clipped to the nearest sentence boundary "
            "to give the encoder polysemy-resolving context. May be "
            "empty if the span is at the very start of the document."
        ),
    )
    context_after: str = Field(
        default="",
        description=(
            "Up to ~50 chars of CV text immediately following "
            ":attr:`text_span`, clipped to the nearest sentence "
            "boundary. May be empty if the span is at end of document."
        ),
    )
    query_text: str = Field(
        default="",
        description=(
            "Step 5.2 — the **sliding-window text** used as the encoder "
            "query at training time. Identical in shape to what "
            ":func:`skill_matcher.sliding_window.generate_windows` "
            "produces at serving time (30 tokens, ~150-200 chars). "
            "When non-empty, this string is what the encoder sees as the "
            "anchor side of an SBERT pair (see "
            ":func:`skill_matcher.training_data.build_anchor_text`). "
            "When empty (legacy datasets from Step 5 round 1), the "
            "encoder falls back to ``context_before + text_span + "
            "context_after``. Backward-compatible default ensures old "
            "JSONL files still load."
        ),
    )
    window_start: int = Field(
        default=-1,
        description=(
            "Step 5.2 — character offset (inclusive) of the sliding "
            "window in the source CV text. ``-1`` when the pair was "
            "produced from a legacy (anchor-based) build. Allows "
            "ablations that re-tokenise the window without re-running "
            "Module 1."
        ),
    )
    window_end: int = Field(
        default=-1,
        description=(
            "Step 5.2 — character offset (exclusive) of the sliding "
            "window in the source CV text. ``-1`` for legacy pairs."
        ),
    )
    esco_uri: str = Field(
        min_length=1,
        description=(
            "ESCO URI (or ``CUST:...``) of the **labelled** concept "
            "for this pair. For :class:`TrainingPair` this is the "
            "ground-truth positive label; for :class:`HardNegative` "
            "this is the distractor (wrong) URI."
        ),
    )
    surface_form: str = Field(
        min_length=1,
        description=(
            "The surface form Module 2 matched on. Usually equal to "
            ":attr:`text_span` but kept separately for parity with "
            "Module 2's ``SkillMatch`` so future analyses can join on "
            "either field."
        ),
    )
    section: Section = Field(
        description=(
            "Primary CV section the span was assigned to by Module 2's "
            ":class:`~skill_extractor.sections.detector.SectionDetector`."
        ),
    )
    language: Language = Field(
        description=(
            "ISO 639-1 language of the source CV (``\"en\"`` or "
            "``\"ro\"``). Drives encoder model selection downstream."
        ),
    )
    module2_confidence: float = Field(
        ge=0.0,
        le=1.0,
        description=(
            "Module 2's ``SkillMatch.confidence`` for the positive that "
            "this pair was derived from. For :class:`HardNegative` "
            "this is the confidence of the **paired positive**, not "
            "any confidence about the distractor itself."
        ),
    )

    @field_validator("span_end")
    @classmethod
    def _validate_span_order(cls, v: int, info: object) -> int:
        """``span_end`` must strictly exceed ``span_start``."""
        data = getattr(info, "data", {})
        span_start = data.get("span_start")
        if span_start is not None and v <= span_start:
            raise ValueError(
                f"Invalid span: span_end={v} must be > span_start={span_start}."
            )
        return v


class TrainingPair(_PairBase):
    """One distantly-supervised positive ``(text_span, esco_uri)`` pair.

    Generated by Phase D of ``scripts/build_training_dataset.py`` from
    every ``SkillMatch`` whose confidence is at or above the build
    script's ``--min-confidence`` threshold. One pair is emitted per
    ``(URI, span)`` occurrence — i.e. a ``SkillMatch`` that lists three
    spans yields three positives, each with its own context window.
    """

    pair_type: Literal["positive"] = "positive"


class HardNegative(_PairBase):
    """One hard-negative ``(text_span, wrong_esco_uri)`` pair.

    Generated by Phase E of ``scripts/build_training_dataset.py``. Each
    positive yields a fixed number of hard negatives (default 3); the
    strategy mix is biased toward :data:`NegativeStrategy`
    ``same_category_esco`` and ``module2_fp_catalogue``, with
    ``random_in_corpus`` only as a fallback.
    """

    pair_type: Literal["hard_negative"] = "hard_negative"
    negative_strategy: NegativeStrategy = Field(
        description="Which mining strategy selected the distractor URI.",
    )
    paired_with_positive_id: str = Field(
        min_length=1,
        description=(
            "``pair_id`` of the :class:`TrainingPair` this negative was "
            "generated against. Enables ablation studies that filter "
            "or pair up positives and their negatives."
        ),
    )
    distractor_reason: str = Field(
        default="",
        description=(
            "Free-text human-readable explanation of why this distractor "
            "was chosen — e.g. ``\"sibling under L2 'computer "
            "programming'\"`` or ``\"FP family: ML acronym → ML "
            "programming language\"``. Useful for thesis-defence "
            "explanations and for spot-checking the miner."
        ),
    )


# Discriminated union of the two pair types. ``Annotated[..., Field(
# discriminator="pair_type")]`` lets pydantic v2 pick the right subclass
# during validation based solely on the ``pair_type`` field — much
# faster than try/except on both subclasses.
AnyPair = Annotated[
    TrainingPair | HardNegative,
    Field(discriminator="pair_type"),
]

_PAIR_ADAPTER: TypeAdapter[AnyPair] = TypeAdapter(AnyPair)


# ---------------------------------------------------------------------------
# Dataset wrapper
# ---------------------------------------------------------------------------


class TrainingDataset(BaseModel):
    """Wrapper around the in-memory representation of one JSONL split.

    Carries the pair list plus build provenance so the on-disk JSONL
    can be round-tripped and re-built deterministically. The
    ``build_config`` dict mirrors the CLI args the build script was
    invoked with (one entry per argparse flag) — this is the answer to
    the defence question *"cum reproducem rezultatele?"*.
    """

    pairs: list[AnyPair] = Field(default_factory=list)
    split: Literal["train", "val"] = Field(
        description="Which split this dataset object represents."
    )
    build_timestamp: datetime = Field(
        description=(
            "UTC timestamp set by the build script when this dataset "
            "was produced."
        ),
    )
    build_config: dict[str, Any] = Field(
        default_factory=dict,
        description="Mirror of the build script's CLI args.",
    )
    total_cvs_processed: int = Field(
        ge=0,
        description=(
            "Number of training CVs that contributed at least one pair "
            "(positive or negative) to this split."
        ),
    )
    total_cvs_excluded: int = Field(
        ge=0,
        description=(
            "Number of training CVs that were excluded — by Module 1 "
            "failure, ``NotACV`` warning, dedup, or zero confident "
            "Module 2 matches."
        ),
    )


# ---------------------------------------------------------------------------
# Deterministic helpers
# ---------------------------------------------------------------------------


def compute_pair_id(
    cv_id: str,
    span_start: int,
    span_end: int,
    esco_uri: str,
    pair_type: Literal["positive", "hard_negative"],
) -> str:
    """Compute the stable ``pair_id`` for a pair.

    Deterministic SHA-1 of the joined fields, truncated to 16 hex chars.
    SHA-1 is used only as a content hash here (not for cryptographic
    security) — its 16-hex-char prefix gives ~1 in 2⁶⁴ collision odds,
    which is far more than enough for the few-thousand-pair scale.

    Parameters
    ----------
    cv_id
        Source CV identifier (``train_cv042``).
    span_start, span_end
        Character offsets into the source CV text.
    esco_uri
        ESCO or ``CUST:`` URI labelled on this pair.
    pair_type
        ``"positive"`` or ``"hard_negative"`` — included so a positive
        and a negative on the same ``(cv, span, uri)`` triple (which
        cannot happen by construction but is defensible) get distinct
        ids.
    """
    digest_input = f"{cv_id}|{span_start}|{span_end}|{esco_uri}|{pair_type}"
    return hashlib.sha1(digest_input.encode("utf-8")).hexdigest()[:16]


def compute_window_pair_id(
    cv_id: str,
    window_start: int,
    window_end: int,
    span_start: int,
    span_end: int,
    esco_uri: str,
    pair_type: Literal["positive", "hard_negative"],
) -> str:
    """Compute a stable ``pair_id`` for a sliding-window training pair.

    Step 5.2 — same one-way SHA-1 collision-resistant ID scheme as
    :func:`compute_pair_id`, but includes the window's char-offset
    range so two distinct windows over the same span produce distinct
    pair IDs.

    Falls back to the legacy :func:`compute_pair_id` digest when
    ``window_start < 0`` (sentinel for "no window" / legacy build),
    so byte-stability of legacy datasets is preserved.
    """
    if window_start < 0:
        return compute_pair_id(cv_id, span_start, span_end, esco_uri, pair_type)
    digest_input = (
        f"{cv_id}|{window_start}|{window_end}|"
        f"{span_start}|{span_end}|{esco_uri}|{pair_type}"
    )
    return hashlib.sha1(digest_input.encode("utf-8")).hexdigest()[:16]


def _pair_sort_key(pair: AnyPair) -> tuple[str, int, int, str, str]:
    """Sort key that produces byte-identical re-builds.

    Ordering: ``(cv_id, span_start, span_end, pair_type, esco_uri)``.
    ``pair_type`` precedes ``esco_uri`` so a positive and its
    associated hard negatives sit next to each other in the file —
    useful when eyeballing the JSONL during debugging.
    """
    return (pair.cv_id, pair.span_start, pair.span_end, pair.pair_type, pair.esco_uri)


