# Maximum acceptable fraction of malformed rows in a JSONL file before the
# loader gives up. 5 % is permissive enough to survive an occasional
# manual hand-edit but tight enough to catch a truly corrupted file.
_MAX_MALFORMED_FRACTION = 0.05


def save_training_dataset(dataset: TrainingDataset, path: Path) -> None:
    """Write ``dataset`` to ``path`` as JSON-lines.

    The first line is a header object carrying the build metadata
    (``split``, ``build_timestamp``, ``build_config``,
    ``total_cvs_processed``, ``total_cvs_excluded``). The remaining
    lines are one pair each, sorted by :func:`_pair_sort_key` for
    determinism.

    Parameters
    ----------
    dataset
        In-memory dataset to serialise. Must have the pair list already
        populated — empty datasets are allowed (they still emit a
        header).
    path
        Destination JSONL file. Parent directories are created on
        demand. An existing file is overwritten.
    """
    path.parent.mkdir(parents=True, exist_ok=True)

    header: dict[str, Any] = {
        "record_kind": "header",
        "split": dataset.split,
        "build_timestamp": dataset.build_timestamp.isoformat(),
        "build_config": dataset.build_config,
        "total_cvs_processed": dataset.total_cvs_processed,
        "total_cvs_excluded": dataset.total_cvs_excluded,
        "pair_count": len(dataset.pairs),
    }

    sorted_pairs = sorted(dataset.pairs, key=_pair_sort_key)

    with path.open("w", encoding="utf-8", newline="\n") as fp:
        fp.write(json.dumps(header, sort_keys=True, ensure_ascii=False))
        fp.write("\n")
        for pair in sorted_pairs:
            # ``model_dump`` then ``json.dumps(sort_keys=True)`` instead
            # of ``model_dump_json`` because pydantic does not guarantee
            # field order inside ``model_dump_json`` output, and we want
            # byte-identical re-builds.
            payload = pair.model_dump(mode="json")
            payload["record_kind"] = "pair"
            fp.write(json.dumps(payload, sort_keys=True, ensure_ascii=False))
            fp.write("\n")

    logger.info(
        "dataset.saved",
        path=str(path),
        split=dataset.split,
        pair_count=len(sorted_pairs),
    )


def load_training_dataset(path: Path) -> TrainingDataset:
    """Read a JSONL training dataset from ``path``.

    Malformed pair rows are skipped with a ``structlog`` warning; if
    the fraction of skipped rows exceeds
    :data:`_MAX_MALFORMED_FRACTION` the loader raises :class:`ValueError`
    rather than silently returning a degraded dataset (that fail-loud
    behaviour is what the slow invariants test relies on).

    Parameters
    ----------
    path
        Source JSONL file. Must have been produced by
        :func:`save_training_dataset` (or follow the same schema).

    Returns
    -------
    TrainingDataset
        Fully validated dataset, pairs in their on-disk order.
    """
    if not path.exists():
        raise FileNotFoundError(f"Training dataset file not found: {path}")

    pairs: list[AnyPair] = []
    header: dict[str, Any] | None = None
    total_rows = 0
    malformed = 0

    with path.open("r", encoding="utf-8") as fp:
        for line_number, raw in enumerate(fp, start=1):
            stripped = raw.strip()
            if not stripped:
                continue
            try:
                row = json.loads(stripped)
            except json.JSONDecodeError as exc:
                logger.warning(
                    "dataset.malformed_json",
                    path=str(path),
                    line=line_number,
                    error=str(exc),
                )
                malformed += 1
                continue

            kind = row.get("record_kind")
            if kind == "header":
                header = row
                continue

            # Default record_kind to "pair" so JSONL files produced by
            # an earlier schema version still load.
            total_rows += 1
            try:
                # Strip the bookkeeping field before validation — it is
                # not part of the pydantic model.
                row_copy = {k: v for k, v in row.items() if k != "record_kind"}
                pair = _PAIR_ADAPTER.validate_python(row_copy)
            except ValidationError as exc:
                logger.warning(
                    "dataset.malformed_pair",
                    path=str(path),
                    line=line_number,
                    error=str(exc),
                )
                malformed += 1
                continue
            pairs.append(pair)

    if header is None:
        raise ValueError(
            f"Training dataset file is missing a header row: {path}"
        )

    if total_rows > 0 and (malformed / max(total_rows, 1)) > _MAX_MALFORMED_FRACTION:
        raise ValueError(
            f"Too many malformed rows in {path}: {malformed}/{total_rows} "
            f"exceeds {_MAX_MALFORMED_FRACTION:.0%} tolerance."
        )

    dataset = TrainingDataset(
        pairs=pairs,
        split=header["split"],
        build_timestamp=datetime.fromisoformat(header["build_timestamp"]),
        build_config=header.get("build_config", {}),
        total_cvs_processed=int(header.get("total_cvs_processed", 0)),
        total_cvs_excluded=int(header.get("total_cvs_excluded", 0)),
    )

    logger.info(
        "dataset.loaded",
        path=str(path),
        split=dataset.split,
        pair_count=len(pairs),
        malformed=malformed,
    )
    return dataset


